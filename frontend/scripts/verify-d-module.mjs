import { readFileSync, existsSync } from 'node:fs'
const root = new URL('../src/', import.meta.url)
const required = ['views/Login.vue', 'views/TenantAdmin.vue', 'views/Workbench.vue', 'views/ApiKeys.vue', 'views/Playground.vue', 'views/Billing.vue', 'components/StateWrapper.vue', 'components/charts/TrendLine.vue', 'components/charts/KeyPie.vue', 'components/charts/LatencyBar.vue']
for (const path of required) if (!existsSync(new URL(path, root))) throw new Error(`缺少 D 模块前端文件: ${path}`)
const router = readFileSync(new URL('router.js', root), 'utf8')
for (const path of ['/login', '/admin', '/workbench', '/keys', '/playground', '/billing']) if (!router.includes(`'${path}'`)) throw new Error(`缺少路由: ${path}`)
const auth = readFileSync(new URL('auth.js', root), 'utf8')
for (const role of ['super_admin', 'admin', 'readonly']) if (!auth.includes(role)) throw new Error(`缺少角色规则: ${role}`)
for (const marker of ['defaultRouteForRole', 'canAccessRoute', 'roleLabel']) if (!auth.includes(marker)) throw new Error(`缺少权限函数: ${marker}`)
const login = readFileSync(new URL('views/Login.vue', root), 'utf8')
for (const marker of ['smartqa_role', 'smartqa_username', 'smartqa_tenant', 'defaultRouteForRole']) if (!login.includes(marker)) throw new Error(`登录页缺少角色分流: ${marker}`)
for (const marker of ['canAccessRoute', "reason: 'forbidden'", 'defaultRouteForRole']) if (!router.includes(marker)) throw new Error(`路由守卫缺少权限处理: ${marker}`)
const app = readFileSync(new URL('App.vue', root), 'utf8')
for (const marker of ['roleLabel', '只读模式', 'reason', 'smartqa_username', 'smartqa_tenant']) if (!app.includes(marker)) throw new Error(`应用外壳缺少角色反馈: ${marker}`)
if (!app.includes("previous==='login'")) throw new Error('应用外壳没有在切换账号后刷新身份')
if (!app.includes('user.value=null;forbidden.value=false')) throw new Error('退出登录没有清理旧账号的界面状态')
if (app.includes("['admin','super_admin']")) throw new Error('平台管理员不应自动获得租户 Key 管理菜单')
const playground = readFileSync(new URL('views/Playground.vue', root), 'utf8')
if (!playground.includes('sources')) throw new Error('问答页没有引用来源展示')
const admin = readFileSync(new URL('views/TenantAdmin.vue', root), 'utf8')
if (!admin.includes('/api/admin/usage') || !admin.includes('globalUsage')) throw new Error('租户管理台缺少全局用量概览')
const keys = readFileSync(new URL('views/ApiKeys.vue', root), 'utf8')
if (!keys.includes('/usage') || !keys.includes('keyUsage')) throw new Error('Key 管理页缺少单 Key 用量展示')
console.log('D 模块前端静态验收通过')
